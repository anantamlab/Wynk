/*
  Test helper: the product API's real lifecycle responses (contract/fixtures/
  product-api.lifecycle.v1.json, generated by tests/test_product_api_ui_lifecycle_fixture.py from a
  real experiment, promotion, deployment and invocation on a local fake model) served by a
  route-table `fetch`. Every request is recorded with its headers, so tests can check what the UI
  sent (Idempotency-Key, expected_revision, never an Authorization header).
*/
import fixture from "@/api/contract/fixtures/product-api.lifecycle.v1.json";
import { exchange } from "./productApi";

export interface Recorded {
  status: number;
  body: unknown;
}

export const LIFECYCLE = fixture as unknown as Record<string, Recorded> & { new_order: Record<string, string> };

/** The body of a lifecycle response, typed loosely for assertions and edits. */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export const lc = (name: string): any => {
  const e = LIFECYCLE[name];
  if (!e || !("status" in e)) throw new Error(`no response ${name} in the lifecycle fixture`);
  return structuredClone(e.body);
};

export type Reply = { status: number; body: unknown; headers?: Record<string, string> } | Error;
export interface Call {
  route: string;
  headers: Headers;
  body: unknown;
}

/** A recorded lifecycle response (optionally with response headers). */
export const recorded = (name: string, headers?: Record<string, string>): Reply => ({ status: LIFECYCLE[name].status, body: lc(name), headers });
/** A recorded v1 (dataset flow) response. */
export const v1 = (name: string): Reply => ({ status: exchange(name).response.status, body: exchange(name).response.body });
export const ok = (body: unknown, headers?: Record<string, string>): Reply => ({ status: 200, body, headers });
/** The server's error envelope (api/product.py `_error`). */
export const fail = (status: number, code: string, message = `${code} (test)`, details: Record<string, unknown> = {}): Reply => ({
  status,
  body: { error: { code, message, details } },
});

type Route = Reply | Reply[] | ((call: Call, n: number) => Reply);

/**
 * A fetch answering `"METHOD /api/v1/path"` from a table. An array answers in order and repeats its
 * last reply; a function sees the call and how many times the route was called before.
 */
export function server(routes: Record<string, Route>) {
  const calls: Call[] = [];
  const seen = new Map<string, number>();
  const fetch = async (input: RequestInfo | URL, init?: RequestInit): Promise<Response> => {
    const route = `${init?.method ?? "GET"} ${String(input)}`;
    const headers = new Headers(init?.headers);
    const body = typeof init?.body === "string" ? JSON.parse(init.body) : undefined;
    const call = { route, headers, body };
    calls.push(call);
    const n = seen.get(route) ?? 0;
    seen.set(route, n + 1);
    const r = routes[route];
    const reply = Array.isArray(r) ? r[Math.min(n, r.length - 1)] : typeof r === "function" ? r(call, n) : r;
    if (!reply) return new Response("not routed in test", { status: 599 });
    if (reply instanceof Error) throw reply;
    return new Response(JSON.stringify(reply.body), { status: reply.status, headers: { "Content-Type": "application/json", ...reply.headers } });
  };
  return { fetch: fetch as typeof globalThis.fetch, calls, count: (route: string) => calls.filter((c) => c.route === route).length };
}
